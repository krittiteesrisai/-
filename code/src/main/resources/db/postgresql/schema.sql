ALTER TABLE meeting_rooms ADD COLUMN IF NOT EXISTS image_data BYTEA;
ALTER TABLE meeting_rooms ADD COLUMN IF NOT EXISTS image_content_type VARCHAR(50);
ALTER TABLE equipment ADD COLUMN IF NOT EXISTS image_data BYTEA;
ALTER TABLE equipment ADD COLUMN IF NOT EXISTS image_content_type VARCHAR(50);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    start_time TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    end_time TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    purpose VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_bookings_room FOREIGN KEY (room_id) REFERENCES meeting_rooms (id),
    CONSTRAINT ck_bookings_status CHECK (
        status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'COMPLETED')
    )
);

CREATE TABLE IF NOT EXISTS booking_equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    equipment_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    CONSTRAINT fk_booking_equipment_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT fk_booking_equipment_equipment FOREIGN KEY (equipment_id) REFERENCES equipment (id),
    CONSTRAINT ck_booking_equipment_quantity CHECK (quantity > 0)
);

CREATE TABLE IF NOT EXISTS booking_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    old_status VARCHAR(255),
    new_status VARCHAR(255) NOT NULL,
    changed_by BIGINT,
    changed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_booking_status_history_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT fk_booking_status_history_changed_by FOREIGN KEY (changed_by) REFERENCES users (id),
    CONSTRAINT ck_booking_status_history_old_status CHECK (
        old_status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'COMPLETED')
    ),
    CONSTRAINT ck_booking_status_history_new_status CHECK (
        new_status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'COMPLETED')
    )
);

CREATE INDEX IF NOT EXISTS idx_booking_room_time ON bookings (room_id, start_time, end_time);
CREATE INDEX IF NOT EXISTS idx_booking_user ON bookings (user_id);
CREATE INDEX IF NOT EXISTS idx_booking_equipment_booking ON booking_equipment (booking_id);
CREATE INDEX IF NOT EXISTS idx_booking_equipment_equipment ON booking_equipment (equipment_id);
CREATE INDEX IF NOT EXISTS idx_booking_status_history_booking ON booking_status_history (booking_id);
CREATE INDEX IF NOT EXISTS idx_booking_status_history_changed_by ON booking_status_history (changed_by);
