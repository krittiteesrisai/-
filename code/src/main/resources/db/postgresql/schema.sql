-- PostgreSQL / Aiven bootstrap for an empty application database.
-- Matches the seven JPA entities on branch nuttachai_673380581-8_04.
-- Run explicitly against the intended database, in one transaction, for example:
--   psql --set=ON_ERROR_STOP=1 --single-transaction --file=schema.sql
-- Supply the connection and SSL settings outside this file; do not store passwords here.
-- After initialization, use spring.jpa.hibernate.ddl-auto=validate and
-- spring.sql.init.mode=never in the deployment environment.
-- This nested resource is not executed by Spring Boot's default schema.sql lookup.
-- Re-running preserves existing rows. IF NOT EXISTS does not migrate old tables
-- whose columns or constraints differ; those changes need a reviewed migration.
-- There are no demo accounts, passwords, seed rows, or destructive table operations.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255),
    email VARCHAR(255),
    password VARCHAR(255),
    role VARCHAR(255),
    active BOOLEAN,
    created_at DATE,
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN', 'STAFF'))
);

CREATE TABLE IF NOT EXISTS user_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255),
    phone VARCHAR(255),
    department VARCHAR(255),
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_user_profile_user UNIQUE (user_id),
    CONSTRAINT fk_user_profile_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE IF NOT EXISTS meeting_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    capacity INTEGER NOT NULL,
    floor VARCHAR(20),
    room_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT ck_meeting_rooms_type CHECK (room_type IN ('STANDARD', 'VIP')),
    CONSTRAINT ck_meeting_rooms_status CHECK (status IN ('AVAILABLE', 'MAINTENANCE'))
);

CREATE TABLE IF NOT EXISTS equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    total_quantity INTEGER NOT NULL,
    category VARCHAR(50)
);

